# 4. MultiAgentToolsSystem (System 5)
# ---------------------------------------------------------------------------
@register_system(["multi_agent_tools", "system_5"])
class MultiAgentToolsSystem(OrderingSystem):
    """System 5: Specialized CrewAI multi-agent ordering system with analytical tools.

    Architecture:
    - 3 specialized agents per echelon: DemandAgent, InventoryAgent, ProcurementAgent.
    - Each agent calls dedicated tools and outputs a structured AgentProposal.
    - Simple aggregator (median or conservative from config) combines proposals.
    - Final order is validated and constrained via validate_order.
    - Logs tool calls to DuckDB with expected_tool labels for accuracy tracking.
    """

    def __init__(
        self,
        name: str = "multi_agent_tools",
        config: Optional[Dict[str, Any]] = None,
        llm_client: Optional[LLMClient] = None,
        run_id: Optional[str] = None,
        db_path: Optional[Union[str, Path]] = None,
        **kwargs: Any,
    ):
        super().__init__(name=name, config=config)
        self.config = config or {}
        self.run_id = run_id or f"run_system5_{uuid.uuid4().hex[:8]}"
        self.aggregation_rule: str = self.config.get("aggregation_rule", "median")
        if self.config.get("db_path") is False or db_path is False:
            self.db_path = False
        elif db_path is not None:
            self.db_path = Path(db_path)
        else:
            try:
                self.db_path = get_config().experiment.db_path
            except Exception:
                self.db_path = Path("results/sca_metrics.duckdb")
        self.llm_client = llm_client or LLMClient(mock_mode=True, db_path=self.db_path)

        # Configurable failure modes for testing tool-choice and parameter accuracy
        self.script_wrong_tool: bool = self.config.get("script_wrong_tool", False)
        self.script_wrong_param: bool = self.config.get("script_wrong_param", False)

        # Initialize specialized agents per echelon
        self.agents: Dict[str, Dict[str, Any]] = {}
        for ech in ECHELONS:
            cap = self.get_capacity(ech)
            self.agents[ech] = {
                "demand": DemandAgent(echelon=ech, config=self.config),
                "inventory": InventoryAgent(echelon=ech, config=self.config),
                "procurement": ProcurementAgent(echelon=ech, capacity_limit=cap, config=self.config),
            }

    def get_capacity(self, echelon: str) -> float:
        """Return capacity threshold for an echelon."""
        if echelon == "manufacturer":
            try:
                return float(self.config.get("manufacturer_capacity", get_config().sim.four_echelon.manufacturer_capacity))
            except Exception:
                return 300.0
        return float(self.config.get("max_order", 500.0))

    def decide_orders(self, states: Dict[str, EchelonState]) -> Dict[str, float]:
        """Generate replenishment orders for all echelons using specialized tool agents."""
        orders: Dict[str, float] = {}

        for echelon in ECHELONS:
            if echelon not in states:
                continue
            state = states[echelon]
            step_id = f"step_{state.step}"
            ech_agents = self.agents[echelon]

            # 1. Generate Proposals from each specialized agent
            p_demand = ech_agents["demand"].propose(
                state=state,
                run_id=self.run_id,
                db_path=self.db_path,
                step_id=step_id,
                script_wrong_tool=self.script_wrong_tool,
                script_wrong_param=self.script_wrong_param,
            )

            p_inventory = ech_agents["inventory"].propose(
                state=state,
                run_id=self.run_id,
                db_path=self.db_path,
                step_id=step_id,
                script_wrong_tool=self.script_wrong_tool,
                script_wrong_param=self.script_wrong_param,
            )

            p_procurement = ech_agents["procurement"].propose(
                state=state,
                run_id=self.run_id,
                db_path=self.db_path,
                step_id=step_id,
            )

            proposals = [p_demand, p_inventory, p_procurement]

            # 2. Simple Aggregation (median or conservative from config)
            agg_qty, agg_desc = aggregate_proposals(proposals, rule=self.aggregation_rule)

            # 3. Final Order Validation via validate_order tool
            cap_limit = self.get_capacity(echelon)
            ip = state.inventory + state.pipeline - state.backlog

            val_out = validate_order(
                ValidateOrderInput(
                    proposed_order=agg_qty,
                    inventory_position=ip,
                    min_order=0.0,
                    max_order=cap_limit,
                    capacity_limit=cap_limit if echelon == "manufacturer" else None,
                ),
                db_path=self.db_path,
                run_id=self.run_id,
                step_id=step_id,
                agent_name=f"aggregator_{echelon}",
                expected_tool="validate_order",
                is_correct_tool=True,
                is_parameter_valid=True,
            )

            final_order = float(val_out.validated_order)
            orders[echelon] = final_order

            logger.debug(
                "[%s Step %d] Proposals: D=%.1f, I=%.1f, P=%.1f -> Agg(%s)=%.1f -> Validated=%.1f",
                echelon,
                state.step,
                p_demand.quantity,
                p_inventory.quantity,
                p_procurement.quantity,
                self.aggregation_rule,
                agg_qty,
                final_order,
            )

        return orders

    def compute_accuracy_metrics(self) -> Dict[str, float]:
        """Compute tool-choice and parameter accuracy from DuckDB tool_calls table."""
        try:
            conn = get_duckdb_connection(self.db_path)
            res = conn.execute(
                """
                SELECT
                    count(*) AS total_calls,
                    count(CASE WHEN is_correct_tool THEN 1 END) AS correct_tool_calls,
                    count(CASE WHEN is_parameter_valid THEN 1 END) AS valid_param_calls
                FROM tool_calls
                WHERE run_id = ?
                """,
                [self.run_id],
            ).fetchone()
            conn.close()

            if res and res[0] > 0:
                tot, corr, val = res
                return {
                    "total_tool_calls": tot,
                    "tool_choice_accuracy": round(corr / tot, 4),
                    "parameter_accuracy": round(val / tot, 4),
                }
        except Exception as e:
            logger.debug("Failed to compute accuracy metrics: %s", e)

        return {"total_tool_calls": 0, "tool_choice_accuracy": 1.0, "parameter_accuracy": 1.0}


