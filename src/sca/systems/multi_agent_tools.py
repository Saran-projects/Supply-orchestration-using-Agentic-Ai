# 2. Specialized CrewAI Agents
# ---------------------------------------------------------------------------
class DemandAgent:
    """Specialized Demand Agent that invokes forecast_demand to project requirements."""

    def __init__(self, echelon: str, min_history_for_forecast: int = 2, config: Optional[Dict[str, Any]] = None):
        self.echelon = echelon
        self.min_history = min_history_for_forecast
        self.config = config or {}
        self.crew_agent = Agent(
            role="Demand Forecasting Specialist",
            goal=f"Accurately forecast replenishment demand for the {echelon} echelon using statistical tools",
            backstory=f"Specialized quantitative demand planner for {echelon} analyzing customer demand signals.",
            tools=[forecast_demand_tool],
            verbose=False,
        )

    def determine_expected_tool(self, state: EchelonState) -> str:
        """Deterministic rule: Demand agent must call forecast_demand when history length >= N."""
        if len(state.history_window) >= self.min_history:
            return "forecast_demand"
        return "forecast_demand"

    def propose(
        self,
        state: EchelonState,
        run_id: str,
        db_path: Path,
        step_id: str,
        script_wrong_tool: bool = False,
        script_wrong_param: bool = False,
    ) -> AgentProposal:
        """Execute demand analysis and return structured proposal."""
        expected_tool = self.determine_expected_tool(state)
        agent_name = f"demand_{self.echelon}"

        # 1. Scripted Wrong-Tool Failure Mode (testing tool-choice accuracy)
        if script_wrong_tool:
            # Demand agent mistakenly calls eoq_quantity instead of forecast_demand
            eoq_quantity(
                {"mean_demand": 100.0, "order_fixed_cost": 100.0, "holding_cost_per_unit": 0.5},
                db_path=db_path,
                run_id=run_id,
                step_id=step_id,
                agent_name=agent_name,
                expected_tool=expected_tool,
                is_correct_tool=False,
            )
            return AgentProposal(
                agent_name="demand",
                quantity=float(state.current_demand),
                tools_used=["eoq_quantity"],
                rationale="Scripted wrong tool called: eoq_quantity instead of forecast_demand",
            )

        # 2. Scripted Wrong-Parameter Failure Mode (testing parameter accuracy)
        if script_wrong_param:
            try:
                # Passes negative horizon violating Pydantic schema ge=1
                forecast_demand(
                    {"recent_history": [100.0], "horizon": -5},
                    db_path=db_path,
                    run_id=run_id,
                    step_id=step_id,
                    agent_name=agent_name,
                    expected_tool=expected_tool,
                    is_correct_tool=True,
                    is_parameter_valid=False,
                )
            except Exception:
                pass
            return AgentProposal(
                agent_name="demand",
                quantity=float(state.current_demand),
                tools_used=["forecast_demand"],
                rationale="Scripted wrong parameter called: negative horizon",
            )

        # 3. Normal Valid Execution
        hist = [float(h.demand) for h in state.history_window] if state.history_window else [float(state.current_demand)]
        out = forecast_demand(
            ForecastDemandInput(recent_history=hist, horizon=1, model_type="linear"),
            db_path=db_path,
            run_id=run_id,
            step_id=step_id,
            agent_name=agent_name,
            expected_tool=expected_tool,
            is_correct_tool=True,
            is_parameter_valid=True,
        )

        proposed_qty = max(0.0, float(out.point_forecast))
        return AgentProposal(
            agent_name="demand",
            quantity=proposed_qty,
            tools_used=["forecast_demand"],
            rationale=f"Forecast next step={out.point_forecast:.1f} using linear regression on {len(hist)} steps history.",
        )


class InventoryAgent:
    """Specialized Inventory Agent that invokes eoq_quantity and ss_policy_order."""

    def __init__(self, echelon: str, config: Optional[Dict[str, Any]] = None):
        self.echelon = echelon
        self.config = config or {}
        self.crew_agent = Agent(
            role="Inventory Optimization Specialist",
            goal=f"Optimize cycle stock and safety stocks for {echelon} using Wilson EOQ and (s, S) policies",
            backstory=f"Operations research specialist tracking on-hand inventory positions and setup costs for {echelon}.",
            tools=[eoq_quantity_tool, ss_policy_order_tool],
            verbose=False,
        )

    def determine_expected_tool(self, state: EchelonState) -> str:
        """Deterministic rule: Inventory agent must call eoq_quantity for batch sizing."""
        return "eoq_quantity"

    def propose(
        self,
        state: EchelonState,
        run_id: str,
        db_path: Path,
        step_id: str,
        script_wrong_tool: bool = False,
        script_wrong_param: bool = False,
    ) -> AgentProposal:
        """Execute inventory policy and batch sizing, returning structured proposal."""
        expected_tool = self.determine_expected_tool(state)
        agent_name = f"inventory_{self.echelon}"

        # 1. Scripted Wrong-Tool Failure Mode
        if script_wrong_tool:
            validate_order(
                {"proposed_order": 100.0, "inventory_position": 100.0},
                db_path=db_path,
                run_id=run_id,
                step_id=step_id,
                agent_name=agent_name,
                expected_tool=expected_tool,
                is_correct_tool=False,
            )
            return AgentProposal(
                agent_name="inventory",
                quantity=100.0,
                tools_used=["validate_order"],
                rationale="Scripted wrong tool called: validate_order instead of eoq_quantity",
            )

        # 2. Scripted Wrong-Parameter Failure Mode
        if script_wrong_param:
            try:
                # Passes negative demand violating gt=0.0
                eoq_quantity(
                    {"mean_demand": -50.0, "order_fixed_cost": 100.0, "holding_cost_per_unit": 0.5},
                    db_path=db_path,
                    run_id=run_id,
                    step_id=step_id,
                    agent_name=agent_name,
                    expected_tool=expected_tool,
                    is_correct_tool=True,
                    is_parameter_valid=False,
                )
            except Exception:
                pass
            return AgentProposal(
                agent_name="inventory",
                quantity=100.0,
                tools_used=["eoq_quantity"],
                rationale="Scripted wrong parameter called: negative mean demand",
            )

        # 3. Normal Valid Execution: compute EOQ & (s, S) policy order
        hist = [float(h.demand) for h in state.history_window] if state.history_window else [float(state.current_demand)]
        mean_d = max(1.0, float(np.mean(hist)))

        fixed_cost = float(self.config.get("order_fixed_cost", 100.0))
        holding_cost = float(self.config.get("holding_cost_per_unit", 0.50))
        reorder_point = float(self.config.get("reorder_point", 150.0))
        order_up_to = float(self.config.get("order_up_to", 350.0))

        eoq_out = eoq_quantity(
            EoqQuantityInput(
                mean_demand=mean_d,
                order_fixed_cost=fixed_cost,
                holding_cost_per_unit=holding_cost,
            ),
            db_path=db_path,
            run_id=run_id,
            step_id=step_id,
            agent_name=agent_name,
            expected_tool="eoq_quantity",
            is_correct_tool=True,
            is_parameter_valid=True,
        )

        ss_out = ss_policy_order(
            SsPolicyOrderInput(
                inventory=state.inventory,
                pipeline=state.pipeline,
                backlog=state.backlog,
                reorder_point=reorder_point,
                order_up_to=order_up_to,
            ),
            db_path=db_path,
            run_id=run_id,
            step_id=step_id,
            agent_name=agent_name,
            expected_tool="ss_policy_order",
            is_correct_tool=True,
            is_parameter_valid=True,
        )

        tools_used = ["eoq_quantity", "ss_policy_order"]
        if ss_out.reorder_triggered:
            # Reorder triggered: order up to S or EOQ batch
            proposed_qty = max(float(ss_out.order_quantity), float(eoq_out.eoq))
            rationale = (
                f"Reorder triggered (IP={ss_out.inventory_position:.1f} < s={reorder_point:.1f}). "
                f"Ordering {proposed_qty:.1f} (target S={order_up_to:.1f}, EOQ={eoq_out.eoq:.1f})."
            )
        else:
            proposed_qty = 0.0
            rationale = f"Inventory position ({ss_out.inventory_position:.1f}) is above s ({reorder_point:.1f}); no reorder."

        return AgentProposal(
            agent_name="inventory",
            quantity=proposed_qty,
            tools_used=tools_used,
            rationale=rationale,
        )


class ProcurementAgent:
    """Specialized Procurement Agent checking supplier capacity and transit lead time."""

    def __init__(self, echelon: str, capacity_limit: float = 300.0, config: Optional[Dict[str, Any]] = None):
        self.echelon = echelon
        self.capacity_limit = capacity_limit
        self.config = config or {}
        self.crew_agent = Agent(
            role="Procurement Sourcing Specialist",
            goal=f"Verify upstream supplier capacity and pipeline lead times for {echelon}",
            backstory=f"Strategic supply chain procurement buyer ensuring orders respect supplier constraints for {echelon}.",
            tools=[],
            verbose=False,
        )

    def propose(
        self,
        state: EchelonState,
        run_id: str,
        db_path: Path,
        step_id: str,
    ) -> AgentProposal:
        """Inspect state capacity and lead time, returning a constrained procurement proposal."""
        shortfall = max(0.0, state.current_demand + state.backlog - state.inventory)
        lead_time_buffer = float(state.lead_time) * (state.current_demand * 0.4)
        desired_order = shortfall + max(0.0, lead_time_buffer - state.pipeline)

        # Constrain by supplier capacity
        capped_order = min(self.capacity_limit, desired_order)
        final_qty = max(0.0, round(capped_order, 1))

        rationale = (
            f"Observed lead time={state.lead_time}, pipeline={state.pipeline:.1f}, "
            f"shortfall={shortfall:.1f}, supplier capacity ceiling={self.capacity_limit:.1f}."
        )

        return AgentProposal(
            agent_name="procurement",
            quantity=final_qty,
            tools_used=[],
            rationale=rationale,
        )


# ---------------------------------------------------------------------------
# 3. Simple Aggregator
# ---------------------------------------------------------------------------
def aggregate_proposals(proposals: List[AgentProposal], rule: str = "median") -> Tuple[float, str]:
    """Combine agent proposals according to configured aggregation rule without negotiation.

    Supported rules:
    - 'median': Median of proposals (robust against outliers)
    - 'conservative' / 'min': Most conservative (minimum order quantity)
    - 'mean': Arithmetic average
    """
    quantities = [p.quantity for p in proposals]
    if not quantities:
        return 0.0, "No proposals to aggregate"

    r = rule.lower().strip()
    if r in ("conservative", "min"):
        agg_val = float(min(quantities))
        desc = f"Conservative min({[round(q, 1) for q in quantities]}) = {agg_val:.1f}"
    elif r == "mean":
        agg_val = float(np.mean(quantities))
        desc = f"Mean({[round(q, 1) for q in quantities]}) = {agg_val:.1f}"
    elif r in ("max", "aggressive"):
        agg_val = float(max(quantities))
        desc = f"Max({[round(q, 1) for q in quantities]}) = {agg_val:.1f}"
    else:  # default 'median'
        agg_val = float(np.median(quantities))
        desc = f"Median({[round(q, 1) for q in quantities]}) = {agg_val:.1f}"

    return agg_val, desc


