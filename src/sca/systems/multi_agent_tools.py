"""Multi-Agent Tool-Using Architecture (System 5).

Implements specialized CrewAI agents (Demand, Inventory, Procurement) that invoke
executable analytical tools to generate structured replenishment proposals.
Proposals are aggregated via a configurable simple aggregator (median or conservative)
and finalized through order validation.

Features:
- Demand Agent: Calls forecast_demand based on observed historical demand.
- Inventory Agent: Calls eoq_quantity (batch sizing) and ss_policy_order (min-max thresholds).
- Procurement Agent: Verifies upstream supplier capacity, lead times, and pipeline state.
- Structured Proposals: Each agent outputs an AgentProposal(agent_name, quantity, tools_used, rationale).
- Aggregator: Combines proposals (median or conservative / min) without complex negotiation.
- Validation: Passes aggregated order through validate_order (no allocate_capacity or Banker's algorithm).
- Telemetry: Logs tool calls to DuckDB with inputs, outputs, and deterministic expected_tool labels
  to evaluate tool-choice and parameter accuracy.
"""

